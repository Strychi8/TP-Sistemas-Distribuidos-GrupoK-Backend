#!/usr/bin/env bash
# Inicializa las bases de datos y los usuarios de los servicios de Rentar.
# MySQL ejecuta este script solo cuando el directorio de datos está vacío.
# Lee los nombres de bases de datos y las credenciales de variables de entorno
# que Docker Compose pasa al contenedor.
set -e

mysql -uroot -p"${MYSQL_ROOT_PASSWORD}" <<EOSQL
CREATE DATABASE IF NOT EXISTS \`${VEHICLE_DB_NAME}\`  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS \`${CUSTOMER_DB_NAME}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS \`${RENTAL_DB_NAME}\`   CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS \`${VERIFICACION_DB_NAME}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS \`${MANTENIMIENTO_DB_NAME}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE USER IF NOT EXISTS '${VEHICLE_DB_USER}'@'%'  IDENTIFIED BY '${VEHICLE_DB_PASSWORD}';
CREATE USER IF NOT EXISTS '${CUSTOMER_DB_USER}'@'%' IDENTIFIED BY '${CUSTOMER_DB_PASSWORD}';
CREATE USER IF NOT EXISTS '${RENTAL_DB_USER}'@'%'   IDENTIFIED BY '${RENTAL_DB_PASSWORD}';
CREATE USER IF NOT EXISTS '${VERIFICACION_DB_USER}'@'%' IDENTIFIED BY '${VERIFICACION_DB_PASSWORD}';
CREATE USER IF NOT EXISTS '${MANTENIMIENTO_DB_USER}'@'%' IDENTIFIED BY '${MANTENIMIENTO_DB_PASSWORD}';

GRANT ALL PRIVILEGES ON \`${VEHICLE_DB_NAME}\`.*  TO '${VEHICLE_DB_USER}'@'%';
GRANT ALL PRIVILEGES ON \`${CUSTOMER_DB_NAME}\`.* TO '${CUSTOMER_DB_USER}'@'%';
GRANT ALL PRIVILEGES ON \`${RENTAL_DB_NAME}\`.*   TO '${RENTAL_DB_USER}'@'%';
GRANT ALL PRIVILEGES ON \`${VERIFICACION_DB_NAME}\`.* TO '${VERIFICACION_DB_USER}'@'%';
GRANT ALL PRIVILEGES ON \`${MANTENIMIENTO_DB_NAME}\`.* TO '${MANTENIMIENTO_DB_USER}'@'%';

FLUSH PRIVILEGES;
EOSQL
